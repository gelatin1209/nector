#!/usr/bin/env bash

_NECTOR_SCRIPT="${BASH_SOURCE[0]:-$0}"
NECTOR_HOME="$(CDPATH= cd -- "$(dirname -- "$_NECTOR_SCRIPT")/.." && pwd)"
NECTOR_VERSION="0.1.0"
NECTOR_LIBRARY="$NECTOR_HOME/library"
NECTOR_INCLUDE="$NECTOR_LIBRARY/include"
NECTOR_STATIC="$NECTOR_LIBRARY/static"
NECTOR_TOOLS="$NECTOR_LIBRARY"
Nector_DIR="$NECTOR_LIBRARY/cmake"
PKG_CONFIG_PATH="$NECTOR_LIBRARY/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
NECTOR_ASSETS="$NECTOR_LIBRARY/assets"
NECTOR_LOCALE="$NECTOR_LIBRARY/locale"
NECTOR_FONT_SOURCE_HAN_SERIF="$NECTOR_ASSETS/source_han_serif_sc.otf"
NECTOR_FONT_SOURCE_HAN_SANS="$NECTOR_ASSETS/source_han_sans_sc.otf"
NECTOR_FONT_NOTO_SANS_CJK="$NECTOR_ASSETS/noto_sans_cjk_sc.otf"
NECTOR_FONT="$NECTOR_ASSETS/deja_vu_sans.ttf"

case "$(uname -s)" in
    Darwin*)
        NECTOR_CONFIG="$NECTOR_HOME/metadata/nector.macos.json"
        export DYLD_LIBRARY_PATH="$NECTOR_LIBRARY${DYLD_LIBRARY_PATH:+:$DYLD_LIBRARY_PATH}"
        ;;
    *)
        NECTOR_CONFIG="$NECTOR_HOME/metadata/nector.linux.json"
        export LD_LIBRARY_PATH="$NECTOR_LIBRARY${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
        ;;
esac

export NECTOR_HOME NECTOR_VERSION NECTOR_LIBRARY NECTOR_INCLUDE NECTOR_STATIC
export NECTOR_TOOLS NECTOR_ASSETS NECTOR_LOCALE NECTOR_CONFIG NECTOR_FONT Nector_DIR PKG_CONFIG_PATH
export NECTOR_FONT_SOURCE_HAN_SERIF NECTOR_FONT_SOURCE_HAN_SANS NECTOR_FONT_NOTO_SANS_CJK
export PATH="$NECTOR_TOOLS:$PATH"
unset _NECTOR_SCRIPT
